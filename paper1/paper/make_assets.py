CONTAM_GUARDS = [  # guards whose training data could be audited, in GUARDS order; PIGuard is audited but not scored
    ("guardshield", "GuardShield (ours)"), ("protectai_v2", "ProtectAI v2"), ("deepset", "deepset"), ("fmops", "fmops"),
    ("horizon_guard_base", "Horizon guard-base"), ("piguard", "PIGuard$^\\dagger$"),
]
CONTAM_COLUMNS = [("obf", "gandalf:attack", ("attack",)), ("obf", "dolly:benign", ("twin", "calibration")),
                  ("pids", "pids_test:attack", ("attack",)), ("pids", "pids_test:benign", ("twin", "calibration"))]
DECON_MIN_PAIRS = 100  # sensitivity analysis is read only for guards keeping at least this many pairs


def contamination(run, pids_run):
    C = {"obf": json.loads((Path(run) / "contamination.json").read_text(encoding="utf-8")),
         "pids": json.loads((Path(pids_run) / "contamination.json").read_text(encoding="utf-8"))}
    D = json.loads((Path(run) / "metrics_decontaminated.json").read_text(encoding="utf-8"))["guards"]
    return C, D


def contam_count(c, guard, pools):
    p = c["guards"][guard]["pools"]
    return sum(p[x]["n_contaminated"] for x in pools), sum(p[x]["n"] for x in pools)


def write_contamination(G, C, D):
    obf = C["obf"]["guards"]
    s = "% contamination audit (contamination.json of obf_main and pids_main; metrics_decontaminated.json)\n"
    s += macro("nAuditCorpora", len(C["obf"]["corpora"]))
    s += macro("nAuditGuards", sum(1 for g in obf.values() if g["corpora"]))

    def counts(tag, guard):
        out = ""
        for pool, name in (("attack", "Attacks"), ("twin", "Twins"), ("calibration", "Cal")):
            k = obf[guard]["pools"][pool]["n_contaminated"]
            out += macro(f"{tag}Contam{name}", k)
        a = obf[guard]["pools"]["attack"]
        return out + macro(f"{tag}ContamAttacksPct", f"{100 * a['n_contaminated'] / a['n']:.0f}")

    for g, tag in (("guardshield", "gs"), ("horizon_guard_base", "horizon"), ("protectai_v2", "protectai"), ("piguard", "piguard")):
        s += counts(tag, g)
    s += macro("gsContamAttacksVerbatim", obf["guardshield"]["pools"]["attack"]["n_verbatim"])
    s += macro("gsContamPairs", len(obf["guardshield"]["contaminated_pairs"]))
    s += macro("pidsAuditTexts", sum(v["n"] for v in C["pids"]["pools"].values()))
    s += macro("pidsContamTexts", len({(m["pool"], m["id"]) for g in C["pids"]["guards"].values() for m in g["matches"]}))

    # sensitivity: each guard without its own contaminated pairs
    cells = changed_mode = changed_mode_fpr = 0
    changed_sig, shifts, guards_read = [], [], []
    for g, d in D.items():
        n_left = d["conditions"]["clean"]["n_pairs"]
        tag = {"guardshield": "gs", "horizon_guard_base": "horizon", "protectai_v2": "protectai"}.get(g)
        if tag:
            s += macro(f"{tag}DeconPairs", n_left)
        if n_left < DECON_MIN_PAIRS:
            continue
        guards_read.append(g)
        for f, _, _ in FAMILIES:
            a, b = G[g]["conditions"][f], d["conditions"][f]
            cells += 1
            changed_mode += a["policies"]["default"]["failure_mode"] != b["policies"]["default"]["failure_mode"]
            changed_mode_fpr += a["policies"]["fpr@0.05"]["failure_mode"] != b["policies"]["fpr@0.05"]["failure_mode"]
            shifts.append(abs(a["auroc"] - b["auroc"]))
            if a["signal"] != b["signal"]:
                changed_sig.append(f"{a['signal']}->{b['signal']}")
    s += macro("deconMinPairs", DECON_MIN_PAIRS) + macro("deconCells", cells)
    s += macro("deconModeChanged", changed_mode) + macro("deconModeFprChanged", changed_mode_fpr)
    s += macro("deconSigChanged", len(changed_sig))
    s += macro("deconSigUp", sum(c == "destroyed->degraded" for c in changed_sig))
    s += macro("deconAucShiftMax", f"{max(shifts):.2f}")
    (OUT / "numbers_contamination.tex").write_text(s, encoding="utf-8")

    rows = []
    for g, n in CONTAM_GUARDS:
        cells = []
        for run, key, pools in CONTAM_COLUMNS:
            guard = C[run]["guards"][g]
            k, total = contam_count(C[run], g, pools)
            cells.append(f"{guard['status'][key]} ({k}/{total})")
        rows.append(f"{n} & " + " & ".join(cells) + " \\\\")
    rest = [n for g, n, kind in GUARDS if kind != "base" and (g not in obf or not obf[g]["corpora"])]
    rows.append(f"\\midrule\nOther {len(rest)} detectors & \\multicolumn{{4}}{{c}}{{unknown (training data undisclosed or gated)}} \\\\")
    (OUT / "tab_contamination.tex").write_text("% columns: guard & Gandalf attacks & Dolly benign & PIDS attacks & PIDS benign\n"
                                               + "\n".join(rows) + "\n", encoding="utf-8")


def write_tables(G):
    # clean condition
    rows = []
    for g, n, kind in GUARDS:
        c = G[g]["conditions"]["clean"]
        p = c["policies"].get("default", {})
        lo, hi = c["auroc_ci95"]
        rows.append(f"{n} & {c['auroc']:.3f} [{lo:.2f}, {hi:.2f}] & {pct(p.get('tpr', {}).get('value'))} & "
                    f"{pct(p.get('fpr', {}).get('value'))} & {pct(p.get('pja', {}).get('value'))} & {pct(c['fpr_at_tpr90'])} \\\\")
    (OUT / "tab_clean.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")

    mark = {"intact": "", "degraded": "\\dg", "destroyed": "\\ds"}
    head = " & ".join(lbl for _, lbl, _ in FAMILIES)
    rows = []
    for g, n, _ in GUARDS:
        cs = G[g]["conditions"]
        rows.append(n + " & " + f"{cs['clean']['auroc']:.2f} & " +
                    " & ".join(f"{mark[cs[f]['signal']]}{cs[f]['auroc']:.2f}" for f, _, _ in FAMILIES) + " \\\\")
    (OUT / "tab_auroc.tex").write_text(f"% columns: guard & clean & {head}\n" + "\n".join(rows) + "\n", encoding="utf-8")

    rows = []
    for g, n, _ in GUARDS:
        cs = G[g]["conditions"]
        vals = [cs[c]["policies"].get("default", {}).get("pja", {}).get("value") for c in ["clean"] + [f for f, _, _ in FAMILIES]]
        rows.append(n + " & " + " & ".join(pct(v, 0) for v in vals) + " \\\\")
    (OUT / "tab_pja.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")


def write_figure(G, stem="fig_failure_map"):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch, Rectangle

    # failure direction at the default threshold; red/blue = diverging poles, gray = no change (validated palette)
    fill = {"fail_closed": "#e34948", "fail_open": "#2a78d6", "both": "#4a3aa7", "stable": "#f0efec", None: "#ffffff"}
    ink = {"fail_closed": "#ffffff", "fail_open": "#ffffff", "both": "#ffffff", "stable": "#52514e", None: "#52514e"}
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 7, "hatch.linewidth": 0.6})
    rows = [(g, n) for g, n, _ in GUARDS]
    fig, ax = plt.subplots(figsize=(6.6, 4.6))
    for i, (g, _) in enumerate(rows):  # column 0: clean AUROC, the reference for every cell in its row
        ax.text(0.5, i + 0.5, f"{G[g]['conditions']['clean']['auroc']:.2f}".lstrip("0"), ha="center", va="center",
                color="#0b0b0b", fontsize=6.2)
        for j, (f, _, _) in enumerate(FAMILIES, start=1):
            c = G[g]["conditions"][f]
            mode = c["policies"].get("default", {}).get("failure_mode")
            ax.add_patch(Rectangle((j + 0.04, i + 0.04), 0.92, 0.92, facecolor=fill[mode], edgecolor="none"))
            if c["signal"] == "destroyed":
                ax.add_patch(Rectangle((j + 0.04, i + 0.04), 0.92, 0.92, facecolor="none", edgecolor=ink[mode],
                                       hatch="////", linewidth=0, alpha=0.35))
            ax.text(j + 0.5, i + 0.5, f"{c['auroc']:.2f}".lstrip("0"), ha="center", va="center",
                    color=ink[mode], fontsize=6.2, fontweight="bold" if c["signal"] != "destroyed" else "normal")
    ax.set_xlim(0, len(FAMILIES) + 1)
    ax.axvline(1, color="#52514e", linewidth=0.6)
    ax.set_ylim(len(rows), 0)
    ax.set_xticks(np.arange(len(FAMILIES) + 1) + 0.5, ["Clean"] + [lbl for _, lbl, _ in FAMILIES], rotation=0)
    ax.set_yticks(np.arange(len(rows)) + 0.5, [n for _, n in rows])
    ax.tick_params(length=0, colors="#52514e")
    ax.xaxis.tick_top()
    for spine in ax.spines.values():
        spine.set_visible(False)
    for y in (11, 17):  # group separators: encoders | judges | baseline
        ax.axhline(y, color="#52514e", linewidth=0.6)
    handles = [Patch(facecolor=fill["fail_closed"], label="fail-closed (benign FPR +20 pts)"),
               Patch(facecolor=fill["fail_open"], label="fail-open (attack recall -20 pts)"),
               Patch(facecolor=fill["both"], label="both"),
               Patch(facecolor=fill["stable"], label="stable"),
               Patch(facecolor="#ffffff", edgecolor="#52514e", hatch="////", label="intent signal destroyed")]
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.45, -0.01), ncol=3, frameon=False,
              fontsize=6.5, handlelength=1.4, columnspacing=1.2)
    fig.tight_layout()
    fig.savefig(OUT / f"{stem}.pdf")
    fig.savefig(OUT / f"{stem}.png", dpi=200)


def write_replication(G, P, manifest):
    """Second primary source (PIDS-Bench): the Study A aggregates again, and cell-level agreement with Study A."""
    A = aggregates(P)
    n_h2, tau, p = kendall_h2(P)
    cells = len(GUARDS) * len(FAMILIES)
    s = "% generated by make_assets.py from pids_main/metrics.json; do not edit\n"
    s += macro("pidsPairs", P["deepset"]["conditions"]["clean"]["n_pairs"])
    origins = manifest["pair_origins"]
    s += macro("pidsTemplateAttacks", origins["attack"].get("template", 0))
    s += macro("pidsSpmlAttacks", origins["attack"].get("spml_injection", 0))
    s += macro("pidsLengthAuc", f"{manifest['pair_length_auroc']:.2f}")
    s += macro("pidsCalibration", P["deepset"]["n_calibration"])
    for k, v in (("Intact", "intact"), ("Degraded", "degraded"), ("Destroyed", "destroyed")):
        s += macro(f"pidsSig{k}", A["sig"][v])
    for k, v in (("Closed", "fail_closed"), ("Open", "fail_open"), ("Both", "both"), ("Stable", "stable")):
        s += macro(f"pidsMode{k}", A["mode_default"][v])
    s += macro("pidsModeCells", sum(A["mode_default"].values()))
    s += macro("pidsAttackRobust", A["attack_robust"]) + macro("pidsAttackRobustFC", A["attack_robust_fc"])
    s += macro("pidsPctAttackRobustFC", f"{100 * A['attack_robust_fc'] / A['attack_robust']:.0f}")
    s += macro("pidsBenignRobust", A["benign_robust"]) + macro("pidsBenignRobustFO", A["benign_robust_fo"])
    for kind in ("wrap", "scaffold"):
        k = A["kind_sig"][kind]
        s += macro(f"pids{kind.capitalize()}Cells", sum(k.values())) + macro(f"pids{kind.capitalize()}Destroyed", k["destroyed"])
        s += macro(f"pids{kind.capitalize()}Intact", k["intact"])
    s += macro("pidsMixedGuards", len(A["mixed"]))
    s += macro("pidsHTwoTau", f"{tau:.2f}") + macro("pidsHTwoP", f"{p:.2f}")

    # agreement with Study A, cell by cell (failure mode at the default threshold; signal status)
    sig_same = mode_same = mode_cells = dir_cells = dir_same = 0
    for g, _, _ in GUARDS:
        for f, _, _ in FAMILIES:
            a, b = G[g]["conditions"][f], P[g]["conditions"][f]
            sig_same += a["signal"] == b["signal"]
            ma = a["policies"].get("default", {}).get("failure_mode")
            mb = b["policies"].get("default", {}).get("failure_mode")
            if ma is None:
                continue
            mode_cells += 1
            mode_same += ma == mb
            if {ma, mb} <= {"fail_closed", "fail_open"}:
                dir_cells += 1
                dir_same += ma == mb
    s += macro("replSigSame", sig_same) + macro("replCells", cells)
    s += macro("replModeSame", mode_same) + macro("replModeCells", mode_cells)
    s += macro("replDirSame", dir_same) + macro("replDirCells", dir_cells)
    s += macro("replMixedSame", len(set(A["mixed"]) & set(aggregates(G)["mixed"])))

    def mean_pja(M, g):
        conds = [c for c in M[g]["conditions"] if c != "clean"]
        return pct(np.mean([M[g]["conditions"][c]["policies"]["default"]["pja"]["value"] for c in conds]))

    def n_destroyed(M, g):
        return sum(c["signal"] == "destroyed" for k, c in M[g]["conditions"].items() if k != "clean")
    for g, tag in (("horizon_guard_base", "horizon"), ("sentinel_v2", "sentinel")):  # Horizon trained on Gandalf
        s += macro(f"{tag}MeanPjaObf", mean_pja(G, g)) + macro(f"{tag}MeanPjaPids", mean_pja(P, g))
        s += macro(f"{tag}DestroyedObf", n_destroyed(G, g)) + macro(f"{tag}DestroyedPids", n_destroyed(P, g))

    def clean(tag, g, metric):
        c = P[g]["conditions"]["clean"]
        if metric == "auroc":
            return macro(tag, f"{c['auroc']:.3f}")
        return macro(tag, pct(c["policies"]["default"][metric]["value"]))
    # external anchors (PIDS-Bench Table 7 reports in-distribution recall 0.369 for Prompt Guard 2 86M)
    s += clean("pidsPgTwoEightSixCleanTPR", "prompt_guard_2_86m", "tpr")
    s += clean("pidsPgTwoEightSixCleanFPR", "prompt_guard_2_86m", "fpr")
    s += clean("pidsProtectaiCleanTPR", "protectai_v2", "tpr") + clean("pidsProtectaiCleanFPR", "protectai_v2", "fpr")
    s += clean("pidsLgThreeOneCleanTPR", "llama_guard_3_1b", "tpr")
    s += clean("pidsDeepsetCleanFPR", "deepset", "fpr") + clean("pidsFmopsCleanFPR", "fmops", "fpr")
    s += clean("pidsPplCleanAUC", "perplexity_gpt2", "auroc")
    enc = [g for g, _, kind in GUARDS if kind != "base" and g != "prompt_guard_v1"]
    aucs = [P[g]["conditions"]["clean"]["auroc"] for g in enc]
    s += macro("pidsCleanAucMin", f"{min(aucs):.2f}") + macro("pidsCleanAucMax", f"{max(aucs):.2f}")
    (OUT / "numbers_pids.tex").write_text(s, encoding="utf-8")
    write_figure(P, stem="fig_failure_map_pids")


