"""
Generates every number, table and figure the paper uses from a run's metrics.json
(paper1/SPEC.md section 8: no hand-entered numbers).

  python paper1/paper/make_assets.py            # Study A, run obf_main

Writes paper1/paper/generated/: numbers.tex (\\newcommand macros), tab_clean.tex, tab_auroc.tex,
tab_pja.tex, fig_failure_map.pdf/.png. Re-run after any metrics change and commit the outputs.
"""

import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np

BASE_DIR = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "generated"

GUARDS = [  # display order: ours, encoder classifiers, content-safety judges, baseline
    ("guardshield", "GuardShield (ours)", "enc"),
    ("protectai_v2", "ProtectAI v2", "enc"),
    ("deepset", "deepset", "enc"),
    ("fmops", "fmops", "enc"),
    ("mezzo_v2_base", "Mezzo PG v2 Base", "enc"),
    ("horizon_guard_base", "Horizon guard-base", "enc"),
    ("sentinel_v2", "Sentinel v2", "enc"),
    ("prompt_guard_v1", "Prompt Guard v1 (inj.)", "enc"),
    ("prompt_guard_v1_jailbreak", "Prompt Guard v1 (jb.)", "enc"),
    ("prompt_guard_2_86m", "Prompt Guard 2 86M", "enc"),
    ("prompt_guard_2_22m", "Prompt Guard 2 22M", "enc"),
    ("llama_guard_3_1b", "Llama Guard 3 1B", "judge"),
    ("llama_guard_3_8b", "Llama Guard 3 8B", "judge"),
    ("llama_guard_4_12b", "Llama Guard 4 12B", "judge"),
    ("qwen3guard_gen_0_6b", "Qwen3Guard-Gen 0.6B", "judge"),
    ("qwen3guard_gen_8b", "Qwen3Guard-Gen 8B", "judge"),
    ("wildguard", "WildGuard", "judge"),
    ("perplexity_gpt2", "GPT-2 perplexity", "base"),
]
FAMILIES = [  # (name, short column label, kind)
    ("zero_width", "ZW", "char"), ("soft_hyphen", "SHY", "char"), ("leetspeak", "Leet", "char"),
    ("homoglyph", "Homo", "char"), ("base64_wrap", "B64", "wrap"), ("base64_scaffold", "B64-S", "scaffold"),
    ("rot13_wrap", "R13", "wrap"), ("rot13_scaffold", "R13-S", "scaffold"),
    ("fullwidth", "FW*", "held"), ("diacritics", "Diac*", "held"), ("spaced_letters", "Spc*", "held"),
]
ROBUST_TPR_DROP, MODE_DELTA = 0.05, 0.20  # "looks robust" = recall within 5 points of clean


def pct(x, nd=1):
    return "--" if x is None else f"{100 * x:.{nd}f}"


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def kendall_h2(G):
    from scipy.stats import kendalltau
    rows = []
    for g, d in G.items():
        conds = [c for c in d["conditions"] if c != "clean"]
        pol = [d["conditions"][c]["policies"].get("default", {}) for c in conds]
        if any(not p.get("tpr") for p in pol):
            continue  # no default threshold (perplexity)
        rows.append((np.mean([p["tpr"]["value"] for p in pol]), np.mean([p["pja"]["value"] for p in pol])))
    t = kendalltau([r[0] for r in rows], [r[1] for r in rows])
    return len(rows), float(t.statistic), float(t.pvalue)


def aggregates(G):
    sig, mode_default, mode_fpr5 = Counter(), Counter(), Counter()
    kind_sig = {k: Counter() for k in ("char", "wrap", "scaffold", "held")}
    attack_robust = attack_robust_fc = benign_robust = benign_robust_fo = 0
    mixed = []
    for g, _, _ in GUARDS:
        d = G[g]
        clean = d["conditions"]["clean"]["policies"].get("default", {})
        dirs = set()
        for f, _, kind in FAMILIES:
            c = d["conditions"][f]
            sig[c["signal"]] += 1
            kind_sig[kind][c["signal"]] += 1
            p = c["policies"].get("default", {})
            mode_fpr5[c["policies"]["fpr@0.05"]["failure_mode"]] += 1
            if not p.get("tpr"):
                continue
            mode_default[p["failure_mode"]] += 1
            dirs |= {p["failure_mode"]} & {"fail_closed", "fail_open"}  # pure cells only; "both" is not counted
            d_tpr = p["tpr"]["value"] - clean["tpr"]["value"]
            d_fpr = p["fpr"]["value"] - clean["fpr"]["value"]
            if d_tpr >= -ROBUST_TPR_DROP:
                attack_robust += 1
                attack_robust_fc += d_fpr >= MODE_DELTA
            if d_fpr <= ROBUST_TPR_DROP:
                benign_robust += 1
                benign_robust_fo += d_tpr <= -MODE_DELTA
        if dirs == {"fail_closed", "fail_open"}:
            mixed.append(g)
    return dict(sig=sig, mode_default=mode_default, mode_fpr5=mode_fpr5, kind_sig=kind_sig,
                attack_robust=attack_robust, attack_robust_fc=attack_robust_fc,
                benign_robust=benign_robust, benign_robust_fo=benign_robust_fo, mixed=mixed)


def write_numbers(m, G, A):
    n_h2, tau, p = kendall_h2(G)
    name = dict((g, n) for g, n, _ in GUARDS)
    lengths = [G["deepset"]["conditions"][f]["length_auroc"] for f in ["clean"] + [f for f, _, _ in FAMILIES]]
    cells = len(GUARDS) * len(FAMILIES)
    s = "% generated by make_assets.py from metrics.json; do not edit\n"
    s += macro("nGuards", len(GUARDS)) + macro("nFamilies", len(FAMILIES)) + macro("nCells", cells)
    s += macro("nPairs", G["deepset"]["conditions"]["clean"]["n_pairs"])
    s += macro("nCalibration", G["deepset"]["n_calibration"])
    s += macro("datasetSha", m["dataset_sha256"][:12])
    for k, v in (("Intact", "intact"), ("Degraded", "degraded"), ("Destroyed", "destroyed")):
        s += macro(f"nSig{k}", A["sig"][v])
    s += macro("pctSigDestroyed", f"{100 * A['sig']['destroyed'] / cells:.0f}")
    for k, v in (("Closed", "fail_closed"), ("Open", "fail_open"), ("Both", "both"), ("Stable", "stable")):
        s += macro(f"nMode{k}", A["mode_default"][v]) + macro(f"nModeFpr{k}", A["mode_fpr5"][v])
    s += macro("nModeCells", sum(A["mode_default"].values()))
    s += macro("nAttackRobust", A["attack_robust"]) + macro("nAttackRobustFC", A["attack_robust_fc"])
    s += macro("pctAttackRobustFC", f"{100 * A['attack_robust_fc'] / A['attack_robust']:.0f}")
    s += macro("nBenignRobust", A["benign_robust"]) + macro("nBenignRobustFO", A["benign_robust_fo"])
    s += macro("pctBenignRobustFO", f"{100 * A['benign_robust_fo'] / A['benign_robust']:.0f}")
    for kind in ("char", "wrap", "scaffold", "held"):
        k = A["kind_sig"][kind]
        tot = sum(k.values())
        K = kind.capitalize()
        s += macro(f"n{K}Cells", tot) + macro(f"n{K}Destroyed", k["destroyed"]) + macro(f"n{K}Intact", k["intact"])
    s += macro("nMixedGuards", len(A["mixed"]))
    s += macro("mixedGuards", ", ".join(name[g] for g in A["mixed"]))
    s += macro("hTwoN", n_h2) + macro("hTwoTau", f"{tau:.2f}") + macro("hTwoP", f"{p:.2f}")
    s += macro("lengthAucMin", f"{min(lengths):.3f}") + macro("lengthAucMax", f"{max(lengths):.3f}")
    n_clean_high = sum(G[g]["conditions"]["clean"]["auroc"] >= 0.95 for g, _, _ in GUARDS)
    s += macro("nCleanAucHigh", n_clean_high)

    def cell(tag, g, f, metric, policy="default"):
        c = G[g]["conditions"][f]
        if metric == "auroc":
            return macro(tag, f"{c['auroc']:.3f}")
        if metric == "auroc_ci":
            lo, hi = c["auroc_ci95"]
            return macro(tag, f"[{lo:.3f}, {hi:.3f}]")
        return macro(tag, pct(c["policies"][policy][metric]["value"]))

    # cells quoted in the text
    s += cell("pgTwoEightSixCleanTPR", "prompt_guard_2_86m", "clean", "tpr")
    for f, tag in (("soft_hyphen", "Shy"), ("leetspeak", "Leet"), ("diacritics", "Diac"), ("base64_wrap", "Bsf")):
        s += cell(f"pgTwoEightSix{tag}TPR", "prompt_guard_2_86m", f, "tpr")
        s += cell(f"pgTwoEightSix{tag}FPR", "prompt_guard_2_86m", f, "fpr")
        s += cell(f"pgTwoEightSix{tag}AUC", "prompt_guard_2_86m", f, "auroc")
    s += cell("pgTwoEightSixHomoAUC", "prompt_guard_2_86m", "homoglyph", "auroc")
    s += cell("pgTwoEightSixHomoTPR", "prompt_guard_2_86m", "homoglyph", "tpr")
    s += cell("pgTwoEightSixZwAUC", "prompt_guard_2_86m", "zero_width", "auroc")
    for f, tag in (("soft_hyphen", "Shy"), ("base64_wrap", "Bsf"), ("rot13_wrap", "Rot"), ("homoglyph", "Homo"), ("fullwidth", "Fw")):
        s += cell(f"protectai{tag}TPR", "protectai_v2", f, "tpr") + cell(f"protectai{tag}FPR", "protectai_v2", f, "fpr")
        s += cell(f"protectai{tag}AUC", "protectai_v2", f, "auroc")
    s += cell("protectaiCleanFPR", "protectai_v2", "clean", "fpr")
    s += cell("protectaiBsfScaffoldFPR", "protectai_v2", "base64_scaffold", "fpr")
    s += cell("protectaiBsfScaffoldAUC", "protectai_v2", "base64_scaffold", "auroc")
    for g, tag in (("llama_guard_4_12b", "lgFour"), ("llama_guard_3_8b", "lgThreeEight")):
        s += cell(f"{tag}CleanTPR", g, "clean", "tpr") + cell(f"{tag}CleanFPR", g, "clean", "fpr")
        for f, ft in (("base64_wrap", "Bsf"), ("rot13_wrap", "Rot"), ("leetspeak", "Leet"), ("fullwidth", "Fw")):
            s += cell(f"{tag}{ft}TPR", g, f, "tpr") + cell(f"{tag}{ft}FPR", g, f, "fpr")
    for f, ft in (("base64_wrap", "Bsf"), ("leetspeak", "Leet"), ("rot13_wrap", "Rot")):
        s += cell(f"qwenSmall{ft}TPR", "qwen3guard_gen_0_6b", f, "tpr") + cell(f"qwenSmall{ft}FPR", "qwen3guard_gen_0_6b", f, "fpr")
    s += cell("guardshieldCleanAUC", "guardshield", "clean", "auroc")
    s += cell("guardshieldCleanFPR", "guardshield", "clean", "fpr")
    s += cell("guardshieldShyFPR", "guardshield", "soft_hyphen", "fpr")
    s += cell("guardshieldShyAUC", "guardshield", "soft_hyphen", "auroc")
    s += cell("horizonCleanAUC", "horizon_guard_base", "clean", "auroc")
    s += cell("pgOneCleanAUC", "prompt_guard_v1", "clean", "auroc")
    s += cell("pgOneCleanFPR", "prompt_guard_v1", "clean", "fpr")
    s += cell("pplCleanAUC", "perplexity_gpt2", "clean", "auroc")
    s += cell("qwenSmallCleanTPR", "qwen3guard_gen_0_6b", "clean", "tpr")
    s += cell("deepsetCleanFPR", "deepset", "clean", "fpr") + cell("fmopsCleanFPR", "fmops", "clean", "fpr")
    judges = [g for g, _, kind in GUARDS if kind == "judge"]
    j_auc = [G[g]["conditions"]["clean"]["auroc"] for g in judges]
    j_tpr = [G[g]["conditions"]["clean"]["policies"]["default"]["tpr"]["value"] for g in judges]
    s += macro("judgeCleanAucMin", f"{min(j_auc):.2f}") + macro("judgeCleanAucMax", f"{max(j_auc):.2f}")
    s += macro("judgeCleanTprMin", pct(min(j_tpr), 0)) + macro("judgeCleanTprMax", pct(max(j_tpr), 0))
    wrap = [(g, f) for g, _, _ in GUARDS for f, _, k in FAMILIES if k == "wrap"]
    s += macro("nWrapNotDestroyed", sum(G[g]["conditions"][f]["signal"] != "destroyed" for g, f in wrap))
    (OUT / "numbers.tex").write_text(s, encoding="utf-8")


def write_tables(G):
    # clean condition
    rows = []
    for g, n, kind in GUARDS:
        c = G[g]["conditions"]["clean"]
        p = c["policies"].get("default", {})
        lo, hi = c["auroc_ci95"]
        rows.append(f"{n} & {c['auroc']:.3f} [{lo:.2f}, {hi:.2f}] & {pct(p.get('tpr', {}).get('value'))} & "
                    f"{pct(p.get('fpr', {}).get('value'))} & {pct(p.get('pja', {}).get('value'))} & {pct(c['fpr_at_tpr90'])} \\\\")
    (OUT / "tab_clean.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")

    mark = {"intact": "", "degraded": "\\dg", "destroyed": "\\ds"}
    head = " & ".join(lbl for _, lbl, _ in FAMILIES)
    rows = []
    for g, n, _ in GUARDS:
        cs = G[g]["conditions"]
        rows.append(n + " & " + f"{cs['clean']['auroc']:.2f} & " +
                    " & ".join(f"{mark[cs[f]['signal']]}{cs[f]['auroc']:.2f}" for f, _, _ in FAMILIES) + " \\\\")
    (OUT / "tab_auroc.tex").write_text(f"% columns: guard & clean & {head}\n" + "\n".join(rows) + "\n", encoding="utf-8")

    rows = []
    for g, n, _ in GUARDS:
        cs = G[g]["conditions"]
        vals = [cs[c]["policies"].get("default", {}).get("pja", {}).get("value") for c in ["clean"] + [f for f, _, _ in FAMILIES]]
        rows.append(n + " & " + " & ".join(pct(v, 0) for v in vals) + " \\\\")
    (OUT / "tab_pja.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")


def write_figure(G):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch, Rectangle

    # failure direction at the default threshold; red/blue = diverging poles, gray = no change (validated palette)
    fill = {"fail_closed": "#e34948", "fail_open": "#2a78d6", "both": "#4a3aa7", "stable": "#f0efec", None: "#ffffff"}
    ink = {"fail_closed": "#ffffff", "fail_open": "#ffffff", "both": "#ffffff", "stable": "#52514e", None: "#52514e"}
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 7, "hatch.linewidth": 0.6})
    rows = [(g, n) for g, n, _ in GUARDS]
    fig, ax = plt.subplots(figsize=(6.6, 4.6))
    for i, (g, _) in enumerate(rows):  # column 0: clean AUROC, the reference for every cell in its row
        ax.text(0.5, i + 0.5, f"{G[g]['conditions']['clean']['auroc']:.2f}".lstrip("0"), ha="center", va="center",
                color="#0b0b0b", fontsize=6.2)
        for j, (f, _, _) in enumerate(FAMILIES, start=1):
            c = G[g]["conditions"][f]
            mode = c["policies"].get("default", {}).get("failure_mode")
            ax.add_patch(Rectangle((j + 0.04, i + 0.04), 0.92, 0.92, facecolor=fill[mode], edgecolor="none"))
            if c["signal"] == "destroyed":
                ax.add_patch(Rectangle((j + 0.04, i + 0.04), 0.92, 0.92, facecolor="none", edgecolor=ink[mode],
                                       hatch="////", linewidth=0, alpha=0.35))
            ax.text(j + 0.5, i + 0.5, f"{c['auroc']:.2f}".lstrip("0"), ha="center", va="center",
                    color=ink[mode], fontsize=6.2, fontweight="bold" if c["signal"] != "destroyed" else "normal")
    ax.set_xlim(0, len(FAMILIES) + 1)
    ax.axvline(1, color="#52514e", linewidth=0.6)
    ax.set_ylim(len(rows), 0)
    ax.set_xticks(np.arange(len(FAMILIES) + 1) + 0.5, ["Clean"] + [lbl for _, lbl, _ in FAMILIES], rotation=0)
    ax.set_yticks(np.arange(len(rows)) + 0.5, [n for _, n in rows])
    ax.tick_params(length=0, colors="#52514e")
    ax.xaxis.tick_top()
    for spine in ax.spines.values():
        spine.set_visible(False)
    for y in (11, 17):  # group separators: encoders | judges | baseline
        ax.axhline(y, color="#52514e", linewidth=0.6)
    handles = [Patch(facecolor=fill["fail_closed"], label="fail-closed (benign FPR +20 pts)"),
               Patch(facecolor=fill["fail_open"], label="fail-open (attack recall -20 pts)"),
               Patch(facecolor=fill["both"], label="both"),
               Patch(facecolor=fill["stable"], label="stable"),
               Patch(facecolor="#ffffff", edgecolor="#52514e", hatch="////", label="intent signal destroyed")]
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.45, -0.01), ncol=3, frameon=False,
              fontsize=6.5, handlelength=1.4, columnspacing=1.2)
    fig.tight_layout()
    fig.savefig(OUT / "fig_failure_map.pdf")
    fig.savefig(OUT / "fig_failure_map.png", dpi=200)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", default=str(BASE_DIR / "paper1" / "runs" / "obf_main"))
    args = p.parse_args()
    m = json.loads((Path(args.run) / "metrics.json").read_text(encoding="utf-8"))
    G = m["guards"]
    missing = [g for g, _, _ in GUARDS if g not in G]
    if missing:
        raise SystemExit(f"metrics.json lacks guards {missing}")
    OUT.mkdir(exist_ok=True)
    A = aggregates(G)
    write_numbers(m, G, A)
    write_tables(G)
    write_figure(G)
    print("wrote", sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
