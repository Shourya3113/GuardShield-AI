"""
Study C driver (paper1/SPEC.md section 2). Steps, each resumable:

  python paper1/study_c/run_study_c.py setup     # run directories study_c_obf and study_c_pids
  python paper1/study_c/run_study_c.py train     # every arm x seed (models/study_c/)
  python paper1/study_c/run_study_c.py guards    # paper1/study_c/guards_study_c.json from the trained models
  python paper1/study_c/run_study_c.py score     # score every Study C guard on both runs
  python paper1/study_c/run_study_c.py metrics   # metrics.json for both runs

Arms per seed: the retrained baseline (none), with the naive canonicalizer, the script-aware canonicalizer
(+ decode-and-rescan) and decode-and-rescan only at inference; augmentation (ratio 1.0); canonicalization +
augmentation. Augmentation ratios 0.25 and 0.5 trace the recall/FPR coupling over training mixtures.
Study C runs live in their own run directories so that Study A's metrics.json keeps exactly its 18 guards.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[2]
RUNS = {"study_c_obf": "obf_main", "study_c_pids": "pids_main"}
SEEDS = [1, 2, 3, 4, 5]
COUPLING_SEEDS = [1, 2, 3]
TRAIN = ([("none", 0.0, s) for s in SEEDS] + [("augment", 1.0, s) for s in SEEDS] +
         [("canon_augment", 1.0, s) for s in SEEDS] +
         [("augment", r, s) for r in (0.25, 0.5) for s in COUPLING_SEEDS])
SHIPPED = ["guardshield", "protectai_v2", "guardshield_canon_naive", "guardshield_canon_script", "guardshield_rescan_only",
           "protectai_v2_canon_naive", "protectai_v2_canon_script", "protectai_v2_rescan_only",
           "guardshield_canon_replace", "protectai_v2_canon_replace"]
GUARDS_FILE = Path(__file__).resolve().parent / "guards_study_c.json"
MODEL_ROOT = BASE_DIR / "models" / "study_c"


def model_name(arm, ratio, seed):
    return f"{arm}_r{ratio:g}_s{seed}"


def setup():
    for run, source in RUNS.items():
        dst, src = BASE_DIR / "paper1" / "runs" / run, BASE_DIR / "paper1" / "runs" / source
        (dst / "scores").mkdir(parents=True, exist_ok=True)
        for f in ("dataset.jsonl", "manifest.json"):
            shutil.copy2(src / f, dst / f)
        for g in SHIPPED:  # shipped checkpoints and their inference-time arms, scored on the identical dataset
            for ext in (".jsonl", ".meta.json"):
                if (src / "scores" / f"{g}{ext}").exists() and not (dst / "scores" / f"{g}{ext}").exists():
                    shutil.copy2(src / "scores" / f"{g}{ext}", dst / "scores" / f"{g}{ext}")
        print(f"{dst}: dataset and shipped-checkpoint scores in place")


def train(attempts: int = 3):
    """Trains every arm x seed not yet trained. A failed run (e.g. a laptop GPU fault) is retried from scratch,
    and the remaining runs continue; failures are listed at the end."""
    failed = []
    for arm, ratio, seed in TRAIN:
        out = MODEL_ROOT / model_name(arm, ratio, seed)
        for attempt in range(attempts):
            if (out / "training_summary.json").exists():
                break
            shutil.rmtree(out, ignore_errors=True)  # partial checkpoints from a failed attempt
            r = subprocess.run([sys.executable, str(Path(__file__).with_name("train_arm.py")), "--arm", arm,
                                "--seed", str(seed), "--ratio", str(ratio)])
            if r.returncode != 0:
                print(f"{out.name}: attempt {attempt + 1} failed (exit {r.returncode})", flush=True)
        if not (out / "training_summary.json").exists():
            failed.append(out.name)
    print("training failures:", failed or "none")


def guards():
    specs = {}
    for summary in sorted(MODEL_ROOT.glob("*/training_summary.json")):
        s = json.loads(summary.read_text(encoding="utf-8"))
        name = f"gs_{model_name(s['arm'], s['ratio'], s['seed'])}"
        base = {"type": "guardshield", "family": "study_c", "model_dir": str(summary.parent.relative_to(BASE_DIR)).replace("\\", "/"),
                "study_c": {"arm": s["arm"], "ratio": s["ratio"], "seed": s["seed"], "inference": "raw"}}
        specs[name] = base
        inference = {"none": [("naive", False, "naive"), ("script_aware", True, "script"), ("none", True, "rescan"),
                              ("script_aware", "replace", "replace")],
                     "canon_augment": [("script_aware", True, "script"), ("script_aware", "replace", "replace")]}.get(s["arm"], [])
        for canon, rescan, tag in inference:
            specs[f"{name}_{tag}"] = {"type": "canonicalized", "family": "study_c", "base": name, "base_spec": base,
                                      "canonicalizer": canon, "rescan": rescan,
                                      "study_c": {**base["study_c"], "inference": tag}}
    GUARDS_FILE.write_text(json.dumps({"_comment": "generated by run_study_c.py guards", "guards": specs}, indent=1),
                           encoding="utf-8")
    print(f"{GUARDS_FILE}: {len(specs)} guards")


def score():
    names = list(json.loads(GUARDS_FILE.read_text(encoding="utf-8"))["guards"])
    for run in RUNS:
        subprocess.run([sys.executable, "-m", "guard_audit.run_audit", "score", "--run", f"paper1/runs/{run}",
                        "--guards-config", str(GUARDS_FILE), "--guards", *names], cwd=BASE_DIR, check=True)


def metrics():
    for run in RUNS:
        subprocess.run([sys.executable, "-m", "guard_audit.run_audit", "metrics", "--run", f"paper1/runs/{run}"],
                       cwd=BASE_DIR, check=True)


def pack():
    """Per-item scores (about 65 MB across both runs) are committed as one LZMA zip per run (about 3 MB)."""
    import zipfile
    for run in RUNS:
        scores = BASE_DIR / "paper1" / "runs" / run / "scores"
        with zipfile.ZipFile(scores.parent / "scores.zip", "w", zipfile.ZIP_LZMA) as z:
            for f in sorted(scores.glob("*.jsonl")):
                z.write(f, f.name)
        print(f"{scores.parent / 'scores.zip'}: {len(list(scores.glob('*.jsonl')))} score files")


def unpack():
    import zipfile
    for run in RUNS:
        run_dir = BASE_DIR / "paper1" / "runs" / run
        with zipfile.ZipFile(run_dir / "scores.zip") as z:
            z.extractall(run_dir / "scores")
        print(f"{run_dir / 'scores'}: restored")


if __name__ == "__main__":
    {"setup": setup, "train": train, "guards": guards, "score": score, "metrics": metrics,
     "pack": pack, "unpack": unpack}[sys.argv[1]]()
